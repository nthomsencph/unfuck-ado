// Generates src/core/primer/icons.gen.ts from @primer/octicons — only the
// icons listed in scripts/icons.txt, because the package's data.json (every
// icon, every size) isn't tree-shakable. Run with `pnpm icons`; the output
// is committed.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const data = require("@primer/octicons/build/data.json");
const pkg = require("@primer/octicons/package.json");

const names = readFileSync("scripts/icons.txt", "utf8")
  .split("\n")
  .map((l) => l.trim())
  .filter((l) => l && !l.startsWith("#"));

const kebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

const icons = {};
for (const name of [...new Set(names)].sort()) {
  const icon = data[name];
  if (!icon) throw new Error(`icons: unknown octicon "${name}" in scripts/icons.txt`);
  icons[name] = {};
  for (const h of ["16", "24"]) {
    const variant = icon.heights[h];
    if (!variant) continue;
    icons[name][h] = {
      w: variant.width,
      paths: variant.ast.children.map((c) => {
        if (c.name !== "path") throw new Error(`icons: ${name}/${h} has a <${c.name}>`);
        return Object.fromEntries(Object.entries(c.attributes).map(([k, v]) => [kebab(k), v]));
      }),
    };
  }
  if (!icons[name]["16"]) throw new Error(`icons: ${name} has no 16px variant`);
}

const out = `// GENERATED by scripts/icons.mjs from @primer/octicons ${pkg.version} — do not edit.
// Edit scripts/icons.txt and run \`pnpm icons\`.

export interface OcticonVariant {
  /** viewBox width; the height is the variant's key. */
  w: number;
  /** Attributes of each <path> (d, fill-rule, …). */
  paths: Record<string, string>[];
}

export const ICONS = {
${Object.entries(icons)
  .map(([name, v]) => `  ${JSON.stringify(name)}: ${JSON.stringify(v)},`)
  .join("\n")}
} satisfies Record<
  string,
  { 16: OcticonVariant; 24?: OcticonVariant }
>;

export type OcticonName = keyof typeof ICONS;
`;
writeFileSync("src/core/primer/icons.gen.ts", out);
console.log(`icons: ${Object.keys(icons).length} octicons → src/core/primer/icons.gen.ts`);
